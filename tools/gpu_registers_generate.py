#!/usr/bin/env python3
# Writes projects/brix/registers/, the registers of the Radeon RX 580
# (Polaris 10: GFX 8, GMC 8.1, OSS 3.0, BIF 5.0, SMU 7.1.3, DCE 11.2) as
# Mlx modules of ours, from the specifications at fixed tags, never by hand:
#
#   tools/gpu_registers_generate.py [--check] [--inputs DIR] [--output DIR]
#
# THE INPUTS are kept unchanged in projects/brix/registers/upstream/ (DIR),
# each as its upstream has it at a fixed tag; upstream/SOURCES names its
# URL, its tag and its sha256, and a file whose sha256 is not the one
# SOURCES gives is refused before it is read:
# - Mesa mesa-24.0.0's register database for GFX8: src/amd/registers/
#   gfx8.json (registers, their byte offsets, fields with their bits,
#   enums) and the GFX8 entries of registers-manually-defined.json (Mesa's
#   own additions: the copy engines' and the system's status words). The
#   JSON is read as data (json.load); nothing of it runs.
# - Linux v6.6's drivers/gpu/drm/amd/include/asic_reg/ headers for the
#   blocks the database does not hold and for the numbers the kernel takes
#   as Linux's own: gca/gfx_8_0 (and gfx_8_0_enum.h), gmc/gmc_8_1,
#   oss/oss_3_0 (the interrupt ring, the host path and both copy engines:
#   Linux has no sdma0/sdma1 headers for VI, these are their registers),
#   bif/bif_5_0, smu/smu_7_1_3, dce/dce_11_2; each block's _d.h (the
#   registers) and _sh_mask.h (their fields). Read as text: every #define
#   of a number.
#
# THE OUTPUT (DIR, by default projects/brix/registers):
# - gfx8.mlx: Mesa's database whole, every register at its BYTE offset (the
#   database's own form; Mesa and the Vulkan driver's packets count so),
#   every field's mask and shift, every enum;
# - one module per Linux block (bif_5_0.mlx, dce_11_2.mlx, gfx_8_0.mlx,
#   gmc_8_1.mlx, oss_3_0.mlx, smu_7_1_3.mlx): the registers SELECTION names
#   at their DWORD index (Linux's mmNAME and the kernel's form; a register
#   of an index space, such as the SMC's, keeps the header's "ix"), each
#   with every field the header gives it, and the enums SELECTION names;
#   dce_11_2.mlx also the display's MMIO numbers as runs (MMIO_RUNS, for a
#   test card that tells the display's registers from the rest).
# A field is NAME__FIELD (its mask) and NAME__FIELD__SHIFT (its lowest
# bit); an enum is a struct of its values.
#
# WHERE THE DATABASE AND LINUX'S HEADERS DIFFER for a register, a field or
# an enum both have (every one of the database's is held against gca and,
# for Mesa's own additions, oss): the generator says it, writes the cases
# into gfx8.mlx's head, and keeps both apart: the database's number in
# gfx8.mlx, Linux's in its block's module, where such a register is always
# generated (SELECTION need not name it). Where the two only cover
# different things (a field or an enum one of them has and the other not)
# that is said too, as coverage.
#
# HOW A NEW REGISTER IS ADDED (never typed: generated): its name as
# Linux's header has it (without "mm"; with "ix" for an index space's) goes
# under its block in projects/brix/registers/SELECTION (an enum of
# gfx_8_0_enum.h: "enum NAME"), then this is run without --check and the
# changed modules are committed with SELECTION. A register of Mesa's
# database is in gfx8.mlx already. A name the header does not have is
# refused. Code names a register through its block's module
# (`const gmc = @import(".../registers/gmc_8_1.mlx")`, `gmc.VM_L2_CNTL`),
# never by its number. A newer tag is taken by putting the new files into
# upstream/, their sha256 into SOURCES and the tag here, and generating
# again: the differences are then the review.
#
# HOW THE GENERATED FILES ARE CHECKED: --check makes every module again
# from the pinned inputs and compares it with the committed one (each
# module's head holds its inputs' sha256, so a changed input changes it);
# it ends with 1 and names the first line that differs when anything does,
# when an input is not its pinned self, or when SELECTION names what no
# header has. tests/520 runs it, and runs it on a changed input and a
# changed module; tests/519 holds the modules against the inputs by a
# parser of its own; tools/check_gpu_registers.py holds where the kernel
# uses each number.
import hashlib
import json
import os
import re
import sys

LINUX_TAG = "v6.6"
MESA_TAG = "mesa-24.0.0"
LINUX_URL = "https://raw.githubusercontent.com/torvalds/linux/v6.6/drivers/gpu/drm/amd/include/asic_reg/"
MESA_URL = "https://gitlab.freedesktop.org/mesa/mesa/-/raw/mesa-24.0.0/src/amd/registers/"
LINUX_DIR = "linux-v6.6/asic_reg/"
MESA_DIR = "mesa-24.0.0/src/amd/registers/"
GENERATED = "GENERATED by tools/gpu_registers_generate.py"

# The Linux blocks: the module, what the block is, the header's directory
# and stem, and whether its enum header is read.
BLOCKS = [
    ("bif_5_0", "the bus interface (BIF 5.0)", "bif/bif_5_0", False),
    ("dce_11_2", "the display engine (DCE 11.2)", "dce/dce_11_2", False),
    ("gfx_8_0", "the graphics block (GCA, GFX 8.0)", "gca/gfx_8_0", True),
    ("gmc_8_1", "the memory controller (GMC 8.1)", "gmc/gmc_8_1", False),
    ("oss_3_0", "the system's blocks: the interrupt ring, the host path, both copy engines (OSS 3.0)", "oss/oss_3_0", False),
    ("smu_7_1_3", "the SMC, its messages and its index space (SMU 7.1.3)", "smu/smu_7_1_3", False),
]
MESA_FILES = ["gfx8.json", "registers-manually-defined.json"]
# The display's MMIO runs: its registers from 0xC0 on (below it the header
# numbers the audio controller's own index space), the aliases left out,
# a gap of more than 16 dwords ending a run.
RUN_FROM = 0xC0
RUN_GAP = 16


class Refused(Exception):
    pass


def here():
    return os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))


def linux_files():
    out = []
    for _, _, stem, enums in BLOCKS:
        out += [LINUX_DIR + stem + "_d.h", LINUX_DIR + stem + "_sh_mask.h"]
        if enums:
            out.append(LINUX_DIR + stem + "_enum.h")
    return out


def inputs_read(directory):
    """Every input's bytes, each held against SOURCES first."""
    sources = os.path.join(directory, "SOURCES")
    if not os.path.exists(sources):
        raise Refused("%s: no SOURCES (the inputs' URLs, tags and sha256)" % sources)
    pinned = {}
    for line in open(sources):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        if len(parts) != 4:
            raise Refused("SOURCES: a line that is not file, URL, tag, sha256: %s" % line)
        pinned[parts[0]] = (parts[1], parts[2], parts[3])
    wanted = linux_files() + [MESA_DIR + name for name in MESA_FILES]
    data = {}
    for name in wanted:
        if name not in pinned:
            raise Refused("SOURCES does not pin %s" % name)
        url, tag, digest = pinned[name]
        tail = name[len(LINUX_DIR):] if name.startswith(LINUX_DIR) else name[len(MESA_DIR):]
        expected_url = (LINUX_URL if name.startswith(LINUX_DIR) else MESA_URL) + tail
        expected_tag = LINUX_TAG if name.startswith(LINUX_DIR) else MESA_TAG
        if url != expected_url or tag != expected_tag:
            raise Refused("SOURCES: %s is pinned to %s at %s, the generator reads %s at %s" % (name, url, tag, expected_url, expected_tag))
        path = os.path.join(directory, name)
        if not os.path.exists(path):
            raise Refused("%s: missing (fetch it from %s)" % (path, url))
        blob = open(path, "rb").read()
        got = hashlib.sha256(blob).hexdigest()
        if got != digest:
            raise Refused("%s: does not match its pinned sha256 (SOURCES: %s, the file: %s)" % (name, digest, got))
        data[name] = blob
    for name in pinned:
        if name not in data:
            raise Refused("SOURCES pins %s, which the generator does not read" % name)
    return data


def defines(blob, name):
    """The header's #defines of numbers, in order: [(name, value)]."""
    out = []
    seen = {}
    for number, line in enumerate(blob.decode("latin-1").split("\n"), 1):
        if not line.startswith("#define"):
            continue
        m = re.match(r"#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)[uUlL]*\s*$", line.rstrip())
        if not m:
            if re.match(r"#define\s+\w+_H\s*$", line.rstrip()):
                continue
            raise Refused("%s:%d: a #define that is not a number: %s" % (name, number, line.strip()))
        key, value = m.group(1), int(m.group(2), 0)
        if key in seen and seen[key] != value:
            raise Refused("%s: %s twice, %#x and %#x" % (name, key, seen[key], value))
        if key not in seen:
            seen[key] = value
            out.append((key, value))
    return out


def enums_of(blob, name):
    """The enum header's enums: {enum: [(entry, value)]}, and their order."""
    text = blob.decode("latin-1")
    out = {}
    order = []
    for m in re.finditer(r"typedef enum (\w+) \{(.*?)\} (\w+);", text, re.S):
        if m.group(1) != m.group(3):
            raise Refused("%s: enum %s named %s at its end" % (name, m.group(1), m.group(3)))
        entries = []
        for item in m.group(2).split(","):
            item = item.strip()
            if not item:
                continue
            e = re.match(r"(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)$", item)
            if not e:
                raise Refused("%s: enum %s: an entry that is not NAME = number: %s" % (name, m.group(1), item))
            entries.append((e.group(1), int(e.group(2), 0)))
        out[m.group(1)] = entries
        order.append(m.group(1))
    return out, order


class Block:
    """A Linux block: its registers (mm and ix) and its fields."""

    def __init__(self, module, what, stem, data):
        self.module = module
        self.what = what
        self.stem = stem
        self.d = LINUX_DIR + stem + "_d.h"
        self.sh = LINUX_DIR + stem + "_sh_mask.h"
        self.registers = []      # (our name, header name, value) in the header's order
        self.by_name = {}
        for key, value in defines(data[self.d], self.d):
            if key.startswith("mm"):
                ours = key[2:]
            elif key.startswith("ix"):
                ours = key
            else:
                raise Refused("%s: %s is no register (neither mm nor ix)" % (self.d, key))
            self.registers.append((ours, key, value))
            self.by_name[ours] = value
        # The fields: REGISTER__FIELD_MASK and REGISTER__FIELD__SHIFT,
        # REGISTER the header's name without mm or ix.
        plain = {}
        for ours, key, value in self.registers:
            plain.setdefault(key[2:], []).append(ours)
        masks = {}
        shifts = {}
        for key, value in defines(data[self.sh], self.sh):
            if key.endswith("__SHIFT"):
                shifts[key[:-len("__SHIFT")]] = value
            elif key.endswith("_MASK"):
                masks[key[:-len("_MASK")]] = value
            else:
                raise Refused("%s: %s is neither a mask nor a shift" % (self.sh, key))
        self.fields = {}         # our register name -> [(field, mask, shift)]
        self.odd = []            # what the header itself gets wrong
        for base, mask in masks.items():
            register = field = None
            at = base.find("__")
            while at > 0:
                if base[:at] in plain:
                    register, field = base[:at], base[at + 2:]
                    break
                at = base.find("__", at + 1)
            if register is None:
                self.odd.append("%s_MASK names no register of %s" % (base, os.path.basename(self.d)))
                continue
            if base not in shifts:
                self.odd.append("%s_MASK has no __SHIFT in %s: left out" % (base, os.path.basename(self.sh)))
                continue
            shift = shifts[base]
            if mask == 0 or (mask & -mask) != (1 << shift):
                self.odd.append("%s: mask %#x, shift %d" % (base, mask, shift))
            for ours in plain[register]:
                self.fields.setdefault(ours, []).append((field, mask, shift))
        for base in shifts:
            if base not in masks:
                self.odd.append("%s__SHIFT has no _MASK in %s: left out" % (base, os.path.basename(self.sh)))
        self.enums = {}
        self.enum_order = []


def mesa_database(data):
    """Mesa's GFX8 registers: [(name, byte offset, [(field, lo, hi, enum)])], enums."""
    main = json.loads(data[MESA_DIR + "gfx8.json"])
    extra = json.loads(data[MESA_DIR + "registers-manually-defined.json"])
    types = dict(main["register_types"])
    enums = dict(main["enums"])
    mappings = []
    for m in main["register_mappings"]:
        if m["chips"] != ["gfx8"]:
            raise Refused("gfx8.json: %s is for %s" % (m["name"], m["chips"]))
        mappings.append((m, "gfx8.json"))
    for m in extra["register_mappings"]:
        if "gfx8" in m["chips"]:
            mappings.append((m, "registers-manually-defined.json"))
            if "type_ref" in m:
                if m["type_ref"] in types and types[m["type_ref"]] != extra["register_types"][m["type_ref"]]:
                    raise Refused("registers-manually-defined.json: type %s other than gfx8.json's" % m["type_ref"])
                types.setdefault(m["type_ref"], extra["register_types"][m["type_ref"]])
    registers = []
    names = set()
    for m, origin in mappings:
        if m["map"]["to"] != "mm":
            raise Refused("%s: %s is mapped to %s" % (origin, m["name"], m["map"]["to"]))
        if m["name"] in names:
            raise Refused("%s: %s twice" % (origin, m["name"]))
        names.add(m["name"])
        at = m["map"]["at"]
        if at % 4:
            raise Refused("%s: %s at %#x, not a dword's" % (origin, m["name"], at))
        fields = []
        if "type_ref" in m:
            for f in types[m["type_ref"]]["fields"]:
                lo, hi = f["bits"]
                if not 0 <= lo <= hi <= 31:
                    raise Refused("%s: %s.%s bits %d..%d" % (origin, m["name"], f["name"], lo, hi))
                if f.get("enum_ref") is not None and f["enum_ref"] not in enums:
                    raise Refused("%s: %s.%s takes enum %s, which is not there" % (origin, m["name"], f["name"], f["enum_ref"]))
                fields.append((f["name"], lo, hi, f.get("enum_ref")))
        registers.append((m["name"], at, fields, origin))
    registers.sort(key=lambda r: (r[1], r[0]))
    return registers, enums


def mask_of(lo, hi):
    return ((1 << (hi - lo + 1)) - 1) << lo


def compare(registers, enums, gca, oss, gca_enums):
    """Mesa's database against Linux's headers: what is the same, what
    differs, what only one has."""
    report = {"same_registers": 0, "same_fields": 0, "same_entries": 0, "elsewhere": [], "other_number": [],
              "not_in_linux": [], "fields_only_mesa": [], "fields_other": [], "whole_word": [], "fields_only_linux": [],
              "enums_only_mesa": [], "entries_other": [], "entries_only_mesa": [], "by_block": {}}
    for name, at, fields, origin in registers:
        index = at // 4
        block = None
        for candidate in (gca, oss):
            if name in candidate.by_name:
                block = candidate
                break
        if block is None:
            if "ix" + name in gca.by_name:
                report["elsewhere"].append((name, at, "ix" + name, gca.by_name["ix" + name]))
                if at != 4 * gca.by_name["ix" + name]:
                    # (Not at four times Linux's number: a number in question.)
                    report["other_number"].append((name, at, "gfx_8_0's index space", gca.by_name["ix" + name]))
                block = gca
                linux_name = "ix" + name
            else:
                report["not_in_linux"].append((name, at))
                continue
        else:
            linux_name = name
            if block.by_name[name] != index:
                report["other_number"].append((name, at, block.module, block.by_name[name]))
            else:
                report["same_registers"] += 1
        if linux_name == name and block.by_name[name] == index:
            report["by_block"].setdefault(block.module, []).append(name)
        theirs = dict((f, (mask, shift)) for f, mask, shift in block.fields.get(linux_name, []))
        mine = {}
        for field, lo, hi, _ in fields:
            mine[field] = mask_of(lo, hi)
            if field in theirs:
                if theirs[field] != (mask_of(lo, hi), lo):
                    report["fields_other"].append((name, field, mask_of(lo, hi), theirs[field][0]))
                else:
                    report["same_fields"] += 1
            else:
                report["fields_only_mesa"].append((name, field, lo, hi))
        for field, (mask, shift) in theirs.items():
            if field in mine:
                continue
            if not fields and mask == 0xFFFFFFFF:
                report["whole_word"].append((name, field))
            else:
                report["fields_only_linux"].append((name, field, mask))
            for other, other_mask in mine.items():
                if other_mask & mask:
                    report["fields_other"].append((name, field + "/" + other, other_mask, mask))
    for enum, body in sorted(enums.items()):
        if enum not in gca_enums:
            report["enums_only_mesa"].append(enum)
            continue
        theirs = dict(gca_enums[enum])
        for entry in body["entries"]:
            if entry["name"] not in theirs:
                report["entries_only_mesa"].append((enum, entry["name"]))
            elif theirs[entry["name"]] != entry["value"]:
                report["entries_other"].append((enum, entry["name"], entry["value"], theirs[entry["name"]]))
            else:
                report["same_entries"] += 1
    return report


def selection(path, blocks):
    """SELECTION: {module: ([register names], [enum names])}."""
    out = dict((b.module, ([], [])) for b in blocks)
    current = None
    if not os.path.exists(path):
        raise Refused("%s: no SELECTION (the registers to generate, beside the modules)" % path)
    for number, line in enumerate(open(path), 1):
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"\[(\w+)\]$", line)
        if m:
            if m.group(1) not in out:
                raise Refused("SELECTION:%d: no block %s" % (number, m.group(1)))
            current = m.group(1)
            continue
        if current is None:
            raise Refused("SELECTION:%d: a name before any [block]" % number)
        block = [b for b in blocks if b.module == current][0]
        m = re.match(r"enum (\w+)$", line)
        if m:
            if m.group(1) not in block.enums:
                raise Refused("SELECTION:%d: %s has no enum %s" % (number, current, m.group(1)))
            out[current][1].append(m.group(1))
            continue
        if not re.match(r"\w+$", line):
            raise Refused("SELECTION:%d: not a register's name: %s" % (number, line))
        if line not in block.by_name:
            hint = " (the header's names have no mm here)" if line.startswith("mm") else ""
            raise Refused("SELECTION:%d: %s has no register %s%s" % (number, os.path.basename(block.d), line, hint))
        if line in out[current][0]:
            raise Refused("SELECTION:%d: %s twice" % (number, line))
        out[current][0].append(line)
    return out


def hexa(value):
    return "0x%X" % value


def head(lines, w):
    for line in lines:
        w(("// " + line).rstrip())
    return w


def wrap(words, width=74):
    """Words into comment lines of at most `width` characters."""
    out = []
    line = ""
    for word in words:
        if line and len(line) + 1 + len(word) > width:
            out.append(line)
            line = word
        else:
            line = word if not line else line + " " + word
    if line:
        out.append(line)
    return out


def digests(names, data):
    width = max(len(os.path.basename(n)) for n in names)
    return ["  %-*s %s" % (width, os.path.basename(n), hashlib.sha256(data[n]).hexdigest()) for n in names]


def runs_of(block):
    numbers = sorted(set(v for ours, key, v in block.registers if key.startswith("mm") and v >= RUN_FROM and not key.endswith("_ALIAS")))
    runs = []
    first = last = numbers[0]
    for v in numbers[1:]:
        if v - last > RUN_GAP:
            runs += [first, last]
            first = v
        last = v
    return runs + [first, last]


def linux_module(block, chosen, data, report):
    names, enum_names = chosen
    # A register the database has in another form is always here too.
    forced = [e[2] for e in report["elsewhere"]] if block.module == "gfx_8_0" else []
    forced += [e[0] for e in report["other_number"] if e[2] == block.module]
    wanted = set(names) | set(forced)
    order = [ours for ours, _, _ in block.registers if ours in wanted]
    out = []
    w = out.append
    field_count = sum(len(block.fields.get(n, [])) for n in order)
    inputs = [block.d, block.sh] + ([LINUX_DIR + block.stem + "_enum.h"] if enum_names else [])
    lines = wrap(("The registers of %s of the Radeon RX 580 (Polaris 10) as Linux %s has them. %s (do not edit:"
                  " generate it again; README.md beside it says how a register is added) from"
                  " drivers/gpu/drm/amd/include/asic_reg/%s, whose sha256 are"
                  % (block.what, LINUX_TAG, GENERATED, " and ".join(n[len(LINUX_DIR):] for n in inputs))).split())
    lines += digests(inputs, data) + [""]
    text = ("%d of the header's %d registers, the ones SELECTION names%s, each with every field the header gives it (%d fields)"
            % (len(order), len(block.registers),
               " and the %d the database has in another form (gfx8.mlx's head names them)" % len(forced) if forced else "",
               field_count))
    if enum_names:
        text += ", and %d of gfx_8_0_enum.h's enums" % len(enum_names)
    text += (". A register is its number as Linux and the kernel count it, the dword index of its MMIO word (the header's"
             " mmNAME without \"mm\"; a register of an index space keeps the header's \"ix\"). NAME__FIELD is a field's"
             " mask, NAME__FIELD__SHIFT its lowest bit; an enum is a struct of its values.")
    lines += wrap(text.split())
    if block.module == "dce_11_2":
        lines += [""] + wrap(("MMIO_RUNS: every register number of the header from %#x on (below it the header numbers the"
                              " audio controller's own index space), the aliases left out, as first and last of runs a gap"
                              " of more than %d dwords ends." % (RUN_FROM, RUN_GAP)).split())
    head(lines, w)
    names_out = set()

    def put(name, value, text):
        if name in names_out:
            raise Refused("%s: %s twice" % (block.module, name))
        names_out.add(name)
        w(text)

    for ours in order:
        w("")
        if ours in forced:
            w("// (Mesa's database has this one in another form: gfx8.mlx.)")
        put(ours, block.by_name[ours], "pub const %s = %s" % (ours, hexa(block.by_name[ours])))
        field_base = ours[2:] if ours.startswith("ix") else ours
        for field, mask, shift in block.fields.get(ours, []):
            put("%s__%s" % (field_base, field), mask, "pub const %s__%s = %s" % (field_base, field, hexa(mask)))
            put("%s__%s__SHIFT" % (field_base, field), shift, "pub const %s__%s__SHIFT = %d" % (field_base, field, shift))
    for enum in sorted(enum_names, key=block.enum_order.index):
        w("")
        w("// The values of %s (gfx_8_0_enum.h)." % enum)
        put(enum, None, "pub const %s = struct {" % enum)
        for entry, value in block.enums[enum]:
            w("    pub const %s = %d" % (entry, value))
        w("}")
    if block.module == "dce_11_2":
        runs = runs_of(block)
        w("")
        w("// The display's MMIO numbers as runs (first, last, first, last, ...).")
        put("MMIO_RUNS", None, "pub const MMIO_RUNS = [_]usize{")
        for k in range(0, len(runs), 8):
            w("    " + ", ".join(hexa(v) for v in runs[k:k + 8]) + ",")
        w("}")
    return "\n".join(out) + "\n", len(order), field_count


def mesa_module(registers, enums, data, report):
    out = []
    w = out.append
    field_count = sum(len(r[2]) for r in registers)
    inputs = [MESA_DIR + name for name in MESA_FILES]
    lines = wrap(("The registers of the Radeon RX 580's graphics block (GFX8, Polaris 10) as Mesa's register database"
                  " has them. %s (do not edit: generate it again; README.md beside it says how a register is added)"
                  " from Mesa %s's src/amd/registers/gfx8.json and the GFX8 entries of registers-manually-defined.json,"
                  " whose sha256 are" % (GENERATED, MESA_TAG)).split()) + digests(inputs, data) + [""]
    lines += wrap(("Every register of the database, %d (%d of gfx8.json, %d of Mesa's own additions), with every field"
                   " (%d) and all %d enums. A register is its BYTE offset in the MMIO space (the database's \"at\", as"
                   " Mesa and the Vulkan driver's packets count it; Linux's and the kernel's dword index is a quarter of"
                   " it: the block modules beside this one). NAME__FIELD is a field's mask, NAME__FIELD__SHIFT its lowest"
                   " bit, and a field that takes an enum names it; an enum is a struct of its values, named as the"
                   " database names it."
                   % (len(registers), sum(1 for r in registers if r[3] == "gfx8.json"),
                      sum(1 for r in registers if r[3] != "gfx8.json"), field_count, len(enums))).split())
    lines += [""]
    lines += wrap(("WHERE THE DATABASE AND LINUX'S HEADERS DIFFER (gca/gfx_8_0_d.h, _sh_mask.h, _enum.h, and"
                   " oss/oss_3_0 for Mesa's additions), kept apart: the database's numbers here, Linux's in its"
                   " block's module.").split())
    held = ("%d registers at the same place in both (%s), %d fields with the same bits, %d enum values the same."
            % (report["same_registers"], ", ".join("%d in %s" % (len(v), k) for k, v in sorted(report["by_block"].items())),
               report["same_fields"], report["same_entries"]))
    lines += wrap(held.split())
    if report["other_number"]:
        lines += wrap(("- At another number in Linux's header: " + ", ".join(
            "%s (here %#x, %s %#x)" % (n, at, m, v) for n, at, m, v in report["other_number"]) + ".").split())
    if report["elsewhere"]:
        lines += wrap(("- %d registers the database places among the MMIO words at four times the number Linux gives them"
                       " in the SQ's index space (its ixNAME, reached through SQ_IND_INDEX and SQ_IND_DATA, never an MMIO"
                       " word): %s; gfx_8_0.mlx has them as Linux has them (ixNAME)."
                       % (len(report["elsewhere"]), " ".join(e[0] for e in report["elsewhere"]))).split())
    if report["fields_other"]:
        lines += wrap(("- Fields at other bits: " + ", ".join("%s.%s (here %#x, Linux %#x)" % f for f in report["fields_other"]) + ".").split())
    if report["entries_other"]:
        lines += wrap(("- Enum values that differ: " + ", ".join("%s.%s (here %d, Linux %d)" % e for e in report["entries_other"]) + ".").split())
    if report["not_in_linux"]:
        lines += wrap(("- Registers no Linux header has: " + " ".join(n for n, _ in report["not_in_linux"]) + ".").split())
    lines += wrap(("COVERAGE, no number in question: %d fields only the database names (%s); %d registers the database"
                   " leaves without fields to which Linux gives one field that is the whole word (%s ...); %d fields only"
                   " Linux names of registers the database describes%s; %d enums only the database has, by names of its"
                   " own (%s)%s."
                   % (len(report["fields_only_mesa"]),
                      ", ".join("%s.%s, bits %d..%d" % f for f in report["fields_only_mesa"]),
                      len(report["whole_word"]), " ".join("%s.%s" % f for f in report["whole_word"][:3]),
                      len(report["fields_only_linux"]),
                      (" (" + ", ".join("%s.%s" % (n, f) for n, f, _ in report["fields_only_linux"]) + ")") if report["fields_only_linux"] else "",
                      len(report["enums_only_mesa"]), " ".join(report["enums_only_mesa"]),
                      ("; enum values only the database has: " + ", ".join("%s.%s" % e for e in report["entries_only_mesa"])) if report["entries_only_mesa"] else "")).split())
    head(lines, w)
    names_out = set()

    def put(name, text):
        if name in names_out:
            raise Refused("gfx8: %s twice" % name)
        names_out.add(name)
        w(text)

    elsewhere = dict((e[0], e) for e in report["elsewhere"])
    for name, at, fields, origin in registers:
        w("")
        if name in elsewhere:
            w("// (Linux: %s %#x, a word of the SQ's index space.)" % (elsewhere[name][2], elsewhere[name][3]))
        if origin != "gfx8.json":
            w("// (One of Mesa's own additions, registers-manually-defined.json.)")
        put(name, "pub const %s = %s" % (name, hexa(at)))
        for field, lo, hi, enum in fields:
            put("%s__%s" % (name, field), "pub const %s__%s = %s%s" % (name, field, hexa(mask_of(lo, hi)), " // %s" % enum if enum else ""))
            put("%s__%s__SHIFT" % (name, field), "pub const %s__%s__SHIFT = %d" % (name, field, lo))
    # The enums: a module of their own, for the database names some of
    # them as the field that takes them (PA_SU_SC_MODE_CNTL__POLY_MODE).
    enum_out = []
    e = enum_out.append
    head(wrap(("The enums of the Radeon RX 580's graphics block (GFX8, Polaris 10) as Mesa's register database has"
               " them, beside gfx8.mlx, whose fields name the one each takes. %s (do not edit: generate it again;"
               " README.md beside it says how) from Mesa %s's src/amd/registers/gfx8.json, whose sha256 is"
               % (GENERATED, MESA_TAG)).split()) + digests([MESA_DIR + "gfx8.json"], data) + [""] +
         wrap(("All %d enums of the database, each a struct of its values, by the names the database gives them (a module"
               " of their own: some are named as the field that takes them). Linux's gfx_8_0_enum.h has the same values"
               " for every enum both have; gfx8.mlx's head names the ones only the database has."
               % len(enums)).split()), e)
    for enum in sorted(enums):
        e("")
        if not re.match(r"[A-Za-z_]\w*$", enum):
            raise Refused("gfx8.json: an enum named %r" % enum)
        e("pub const %s = struct {" % enum)
        seen = set()
        for entry in enums[enum]["entries"]:
            if not re.match(r"[A-Za-z_]\w*$", entry["name"]) or entry["name"] in seen:
                raise Refused("gfx8.json: enum %s's entry %r" % (enum, entry["name"]))
            seen.add(entry["name"])
            e("    pub const %s = %d" % (entry["name"], entry["value"]))
        e("}")
    return "\n".join(out) + "\n", "\n".join(enum_out) + "\n", len(registers), field_count


def generate(inputs, output):
    data = inputs_read(inputs)
    blocks = [Block(module, what, stem, data) for module, what, stem, _ in BLOCKS]
    for (module, _, stem, enums), block in zip(BLOCKS, blocks):
        if enums:
            name = LINUX_DIR + stem + "_enum.h"
            block.enums, block.enum_order = enums_of(data[name], name)
    gca = [b for b in blocks if b.module == "gfx_8_0"][0]
    oss = [b for b in blocks if b.module == "oss_3_0"][0]
    registers, enums = mesa_database(data)
    report = compare(registers, enums, gca, oss, gca.enums)
    chosen = selection(os.path.join(output, "SELECTION"), blocks)
    texts = {}
    summary = []
    for block in blocks:
        text, count, fields = linux_module(block, chosen[block.module], data, report)
        texts[block.module + ".mlx"] = text
        summary.append("%s %d registers %d fields" % (block.module, count, fields))
    text, enum_text, count, fields = mesa_module(registers, enums, data, report)
    texts["gfx8.mlx"] = text
    texts["gfx8_enums.mlx"] = enum_text
    summary.append("gfx8 %d registers %d fields %d enums" % (count, fields, len(enums)))
    odd = [o for b in blocks for o in b.odd]
    return texts, summary, report, odd


def say_report(report, odd):
    print("Mesa's database against Linux's headers: %d registers, %d fields, %d enum values the same"
          % (report["same_registers"], report["same_fields"], report["same_entries"]))
    for n, at, m, v in report["other_number"]:
        print("  DIFFERS: %s is %#x in the database, %#x (dword) in %s" % (n, at, v, m))
    for n, at, linux, v in report["elsewhere"]:
        print("  DIFFERS: %s is MMIO %#x in the database, Linux's %s is %#x of the SQ's index space" % (n, at, linux, v))
    for f in report["fields_other"]:
        print("  DIFFERS: field %s.%s: the database %#x, Linux %#x" % f)
    for e in report["entries_other"]:
        print("  DIFFERS: enum value %s.%s: the database %d, Linux %d" % e)
    for n, at in report["not_in_linux"]:
        print("  only the database: register %s" % n)
    for f in report["fields_only_mesa"]:
        print("  only the database: field %s.%s (bits %d..%d)" % f)
    print("  only Linux: a whole-word field of %d registers the database leaves without fields" % len(report["whole_word"]))
    for n, f, m in report["fields_only_linux"]:
        print("  only Linux: field %s.%s (%#x)" % (n, f, m))
    for e in report["enums_only_mesa"]:
        print("  only the database: enum %s" % e)
    for e in report["entries_only_mesa"]:
        print("  only the database: enum value %s.%s" % e)
    for o in odd:
        print("  the header itself: %s" % o)


def main(arguments):
    check = False
    root = here()
    inputs = os.path.join(root, "projects", "brix", "registers", "upstream")
    output = os.path.join(root, "projects", "brix", "registers")
    k = 0
    while k < len(arguments):
        a = arguments[k]
        if a == "--check":
            check = True
        elif a in ("--inputs", "--output") and k + 1 < len(arguments):
            if a == "--inputs":
                inputs = arguments[k + 1]
            else:
                output = arguments[k + 1]
            k += 1
        else:
            print("usage: gpu_registers_generate.py [--check] [--inputs DIR] [--output DIR]", file=sys.stderr)
            return 2
        k += 1
    try:
        texts, summary, report, odd = generate(inputs, output)
    except Refused as refusal:
        print("gpu_registers_generate.py: %s" % refusal, file=sys.stderr)
        return 1
    if check:
        wrong = 0
        for name in sorted(texts):
            path = os.path.join(output, name)
            have = open(path).read() if os.path.exists(path) else None
            if have == texts[name]:
                continue
            wrong += 1
            if have is None:
                print("%s: missing" % path)
                continue
            mine, theirs = texts[name].split("\n"), have.split("\n")
            at = next((i for i in range(max(len(mine), len(theirs)))
                       if i >= len(mine) or i >= len(theirs) or mine[i] != theirs[i]), 0)
            print("%s differs from what the pinned inputs give, first at line %d:" % (path, at + 1))
            print("  committed: %s" % (theirs[at] if at < len(theirs) else "(the end)"))
            print("  generated: %s" % (mine[at] if at < len(mine) else "(the end)"))
        for name in sorted(os.listdir(output)):
            if name.endswith(".mlx") and name not in texts and GENERATED in open(os.path.join(output, name)).read(800):
                wrong += 1
                print("%s: generated once, no longer made" % os.path.join(output, name))
        if wrong:
            print("%d of %d modules are not what the pinned inputs give" % (wrong, len(texts)))
            return 1
        print("%d modules are what the pinned inputs give (%s)" % (len(texts), "; ".join(summary)))
        return 0
    for name, text in sorted(texts.items()):
        path = os.path.join(output, name)
        if not os.path.exists(path) or open(path).read() != text:
            with open(path, "w") as handle:
                handle.write(text)
            print("written: %s" % path)
    print("; ".join(summary))
    say_report(report, odd)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
